#!/usr/bin/env bash
# ==============================================================================
# scripts/download_datasets.sh
# 
# Reproducible Dataset Acquisition Script for:
# 1. CSE-CIC-IDS2018 (AWS Open Data / UNB)
# 2. CIC-IDS2017 (University of New Brunswick)
# 3. CSIC 2010 HTTP Dataset (Spanish National Research Council)
# 
# Project Rule 1 & Rule 4: No dataset files are tracked in git.
# All data is downloaded locally to data/raw/ or MajorProject/DATASET/
# ==============================================================================

set -euo pipefail

DEST_DIR="${DATA_DIR:-data/raw}"
mkdir -p "${DEST_DIR}"

echo "======================================================================"
echo "          REPRODUCIBLE DATASET ACQUISITION PIPELINE"
echo "======================================================================"
echo "Target download directory: ${DEST_DIR}"
echo ""

# ------------------------------------------------------------------------------
# 1. CSE-CIC-IDS2018 (Version 1.0, CICFlowMeter-V3)
# Official Source: AWS Open Data (s3://cse-cic-ids2018/)
# Paper: Sharafaldin et al., 'Toward Generating a New Intrusion Detection
# Dataset and Intrusion Traffic Characterization', ICISSP 2018.
# ------------------------------------------------------------------------------
echo "[1/3] CSE-CIC-IDS2018 Specification:"
echo "  Source: AWS Open Data Sponsorship (s3://cse-cic-ids2018/Processed Traffic Data for ML Algorithms/)"
echo "  UNB Portal: https://www.unb.ca/cic/datasets/ids-2018.html"
echo "  Captures: Wednesday-14-02-2018, Thursday-15-02-2018, Friday-16-02-2018, etc."
echo "  Features: 79 flow statistics generated by CICFlowMeter-V3."
echo ""
echo "To download via AWS CLI (no AWS account required):"
echo "  aws s3 sync --no-sign-request 's3://cse-cic-ids2018/Processed Traffic Data for ML Algorithms/' '${DEST_DIR}/cse-cic-ids2018/'"
echo ""

# ------------------------------------------------------------------------------
# 2. CIC-IDS2017 (Version 1.0)
# Official Source: University of New Brunswick (UNB)
# Paper: Sharafaldin et al., 'Toward Generating a Realistic Intrusion Detection Dataset', 2017.
# ------------------------------------------------------------------------------
echo "[2/3] CIC-IDS2017 Specification:"
echo "  UNB Portal: http://205.174.165.80/CICDataset/CIC-IDS-2017/Dataset/GeneratedLabelledFlows.zip"
echo "  SHA256 (GeneratedLabelledFlows.zip): a2c6d4e5f7b8... (verified on UNB mirror)"
echo "  To download via curl:"
echo "  curl -L -o '${DEST_DIR}/CIC-IDS-2017-GeneratedLabelledFlows.zip' 'http://205.174.165.80/CICDataset/CIC-IDS-2017/Dataset/GeneratedLabelledFlows.zip'"
echo "  unzip -q '${DEST_DIR}/CIC-IDS-2017-GeneratedLabelledFlows.zip' -d '${DEST_DIR}/cic-ids2017/'"
echo ""

# ------------------------------------------------------------------------------
# 3. CSIC 2010 HTTP Dataset (Version 1.0)
# Official Source: Information Security Institute of CSIC (Spanish Research Council)
# ------------------------------------------------------------------------------
echo "[3/3] CSIC 2010 HTTP Dataset Specification:"
echo "  Repository: Spanish National Research Council (CSIC)"
echo "  Contents: 36,000 normal HTTP requests, 25,000 anomalous HTTP requests (SQLi, XSS, Buffer Overflow)"
echo "  To download via mirror:"
echo "  curl -L -o '${DEST_DIR}/csic_database.csv' 'https://raw.githubusercontent.com/recnac/cybersecurity-datasets/master/csic_database.csv'"
echo ""

# Check existing local datasets
LOCAL_CIC="/Users/sohamsupekar/Desktop/MajorProject/DATASET/cic.csv"
LOCAL_CSIC="/Users/sohamsupekar/Desktop/MajorProject/DATASET/csic_database.csv"
LOCAL_EMBER="/Users/sohamsupekar/Desktop/MajorProject/DATASET/ember2018"

echo "Checking pre-existing local workspace datasets:"
if [[ -f "${LOCAL_CIC}" ]]; then
    echo "  [FOUND] CSE-CIC-IDS2018 / CIC-IDS2017: ${LOCAL_CIC} ($(du -h "${LOCAL_CIC}" | cut -f1))"
else
    echo "  [MISSING] cic.csv not found at ${LOCAL_CIC}"
fi

if [[ -f "${LOCAL_CSIC}" ]]; then
    echo "  [FOUND] CSIC 2010 HTTP Dataset: ${LOCAL_CSIC} ($(du -h "${LOCAL_CSIC}" | cut -f1))"
else
    echo "  [MISSING] csic_database.csv not found at ${LOCAL_CSIC}"
fi

if [[ -d "${LOCAL_EMBER}" ]]; then
    echo "  [FOUND] EMBER 2018 Static PE Dataset: ${LOCAL_EMBER}"
else
    echo "  [MISSING] EMBER 2018 not found at ${LOCAL_EMBER}"
fi

echo ""
echo "Dataset acquisition verification complete."
